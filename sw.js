const CACHE_NAME = "mmh-builds-shell-v36";
const APP_SHELL = [
  "./",
  "./index.html",
  "./loyalty.js",
  "./catalog.js",
  "./manifest.webmanifest",
  "./assets/mmh-builds-icon-180.png",
  "./assets/mmh-builds-icon-192.png",
  "./assets/mmh-builds-icon-512.png",
  "./assets/hero-pc.svg",
  "./assets/mmh-gaming-setup.png",
  "./assets/graphics-card.svg",
  "./assets/motherboard.svg",
  "./assets/processor.svg",
  "./assets/power-supply.svg"
];

self.addEventListener("install", event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", event => {
  event.waitUntil(
    caches.keys()
      .then(names => Promise.all(names.filter(name => name !== CACHE_NAME).map(name => caches.delete(name))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", event => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  if (new URL(request.url).pathname.split("/").includes("api")) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then(response => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then(cache => cache.put("./index.html", copy));
          }
          return response;
        })
        .catch(() => caches.match("./index.html"))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(cached => cached || fetch(request).then(response => {
      if (response.ok) {
        const copy = response.clone();
        caches.open(CACHE_NAME).then(cache => cache.put(request, copy));
      }
      return response;
    }))
  );
});
